// Writes supabase/apply-migrations.sql: every drizzle migration as one script for the Supabase SQL editor.
// Each migration runs only if drizzle's journal says it has not (the same rule `pnpm db:migrate` uses) and is then
// recorded in the journal with drizzle's own hash, so the SQL editor and `pnpm db:migrate` can be mixed freely.
// Objects are created as `zenhyre_api` (setup.sql granted it to postgres), so the API owns them as with db:migrate.
//   pnpm --filter @zenhyre/db sql:bundle
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const dir = new URL("../drizzle/", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", dir), "utf8"));
const out = [
  "-- GENERATED by `pnpm --filter @zenhyre/db sql:bundle` from packages/db/drizzle. Do not edit by hand.",
  "-- Zenhyre 2.0 schema migrations for the Supabase SQL editor (run as postgres, after setup.sql). Idempotent:",
  "-- applied migrations are skipped, exactly as `pnpm db:migrate` skips them. Equivalent to running `pnpm db:migrate`.",
  `-- Migrations: ${journal.entries.map((e) => e.tag).join(", ")}`,
  "",
  "set role zenhyre_api;",
  'create schema if not exists "zenhyre2";',
  'create table if not exists "zenhyre2"."__drizzle_migrations" (id serial primary key, hash text not null, created_at bigint);',
  "",
];
for (const e of journal.entries) {
  const query = readFileSync(new URL(`${e.tag}.sql`, dir), "utf8");
  if (query.includes("$zh_stmt$")) throw new Error(`${e.tag} contains the quoting tag`);
  const hash = createHash("sha256").update(query).digest("hex");
  const stmts = query.split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean);
  out.push(`-- ${e.tag}`,
    "do $zh_mig$",
    "begin",
    `  if coalesce((select max(created_at) from "zenhyre2"."__drizzle_migrations"), 0) >= ${e.when} then`,
    `    raise notice 'skip ${e.tag} (already applied)';`,
    "    return;",
    "  end if;",
    ...stmts.map((s) => `  execute $zh_stmt$${s}$zh_stmt$;`),
    `  insert into "zenhyre2"."__drizzle_migrations" (hash, created_at) values ('${hash}', ${e.when});`,
    `  raise notice 'applied ${e.tag}';`,
    "end",
    "$zh_mig$;",
    "");
}
out.push("reset role;", "");
writeFileSync(new URL("../supabase/apply-migrations.sql", import.meta.url), out.join("\n"));
console.log(`wrote supabase/apply-migrations.sql (${journal.entries.length} migrations)`);
